"""Generate src/engine/protocol.gen.ts from the Pydantic models in engine/sightline_engine/protocol.py."""
from __future__ import annotations

import sys
import typing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "engine"))

from sightline_engine import protocol as pr  # noqa: E402

OUT = ROOT / "src" / "engine" / "protocol.gen.ts"


def ts_type(s: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return repr(s["const"]).replace("'", '"')
    if "enum" in s:
        return " | ".join(repr(v).replace("'", '"') for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x, defs) for x in s["anyOf"]))
    t = s.get("type")
    if t == "string":
        return "string" if s.get("format") != "binary" else "Uint8Array"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return f"{ts_type(s.get('items', {}), defs)}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def interface(name: str, schema: dict[str, Any], defs: dict[str, Any]) -> str:
    req = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for key, prop in schema.get("properties", {}).items():
        opt = "" if key in req else "?"
        k = key if key.isidentifier() else f'"{key}"'
        lines.append(f"  {k}{opt}: {ts_type(prop, defs)};")
    lines.append("}")
    return "\n".join(lines)


def members(union: Any) -> list[type]:
    return list(typing.get_args(union))


def main() -> None:
    out = ["// Generated by scripts/gen_ts.py from engine/sightline_engine/protocol.py. Do not edit.", ""]
    done: set[str] = set()
    for group in (pr.ClientMessage, pr.EngineMessage):
        for m in members(group):
            sch = m.model_json_schema(by_alias=True)
            defs = sch.get("$defs", {})
            for dn, ds in defs.items():
                if dn not in done:
                    out.append(interface(dn, ds, defs))
                    out.append("")
                    done.add(dn)
            if m.__name__ not in done:
                out.append(interface(m.__name__, sch, defs))
                out.append("")
                done.add(m.__name__)
    out.append("export type ClientMessage = " + " | ".join(m.__name__ for m in members(pr.ClientMessage)) + ";")
    out.append("export type EngineMessage = " + " | ".join(m.__name__ for m in members(pr.EngineMessage)) + ";")
    out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
